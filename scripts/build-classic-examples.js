export function transformClassicExampleMarkup(markup, relativePath) {
  let output = addGeneratedBanner(markup);
  output = addClassicVariantAttribute(output);
  output = rewriteTitle(output);
  output = swapClassicAssets(output);
  output = rewriteModalHooks(output);

  if (relativePath === 'index.html') {
    return transformClassicOverview(output);
  }

  output = rewriteClassicCopy(output, relativePath);

  return output;
}

export async function buildClassicExamples({
  examplesDir = EXAMPLES_DIR,
  outputDir = CLASSIC_EXAMPLES_DIR,
} = {}) {
  await rm(outputDir, { recursive: true, force: true });
  await mkdir(outputDir, { recursive: true });

  const sourceFiles = await collectHtmlFiles(examplesDir);

  await Promise.all(sourceFiles.map(async(sourceFile) => {
    const relativePath = relative(examplesDir, sourceFile);

    if (relativePath === 'summernote-next-classic.html' || relativePath.startsWith('summernote-next-classic/')) {
      return;
    }

    const outputPath = join(outputDir, relativePath);
    const [sourceMarkup] = await Promise.all([
      readFile(sourceFile, 'utf8'),
      mkdir(dirname(outputPath), { recursive: true }),
    ]);

    await writeFile(outputPath, transformClassicExampleMarkup(sourceMarkup, relativePath));
  }));

  return outputDir;
}

export async function classicExamplesExist(path = CLASSIC_EXAMPLES_DIR) {
  try {
    return (await stat(path)).isDirectory();
  } catch {
    return false;
  }
}

